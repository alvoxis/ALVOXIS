let cart =
  JSON.parse(
    localStorage.getItem(
      'alvoxisCartV3'
    ) ||
    '[]'
  );


function saveCart(){

  localStorage.setItem(
    'alvoxisCartV3',
    JSON.stringify(cart)
  );


  renderCart();

}


function renderCart(){

  const box =
    $('#cartItems');


  $('#cartCount')
    .textContent =
    cart.reduce(
      (total,item) =>
        total +
        item.qty,
      0
    );


  if(!cart.length){

    box.innerHTML =
      `
        <p class="backend-note">
          Your cart is empty.
        </p>
      `;


    $('#cartTotal')
      .textContent =
      '€0.00';


    return;

  }


  box.innerHTML =
    cart
      .map(
        (item,index) => `

          <div class="cart-item">

            <img
              src="${item.image}"
              alt=""
            >

            <div>

              <b>
                ${item.product}
              </b>

              <small>
                A4 · 120 pieces<br>
                A6 greeting card<br>
                ${item.message || 'No message'}
              </small>

            </div>

            <div>

              <b>
                €${item.price.toFixed(2)}
              </b>

              <br>

              <button
                class="remove-item"
                data-i="${index}"
              >
                REMOVE
              </button>

            </div>

          </div>

        `
      )
      .join('');


  const total =
    cart.reduce(
      (sum,item) =>
        sum +
        item.price *
        item.qty,
      0
    );


  $('#cartTotal')
    .textContent =
    '€' +
    total.toFixed(2);


  $$('.remove-item')
    .forEach(
      button => {

        button.onclick =
          () => {

            cart.splice(
              Number(
                button.dataset.i
              ),
              1
            );


            saveCart();

          };

      }
    );

}



