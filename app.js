/* =====================================================
   HERO
   SCROLL POSITION CONTROLS VIDEO
===================================================== */

const heroSection =
  $('#hero');

const heroVideo =
  $('#heroVideo');

const heroLayer =
  $('.hero-video-layer');

const heroContent =
  $('#heroContent');

const coverTransition =
  $('#coverTransition');

const coverCard =
  $('.cover-card');


let videoDuration = 0;

let heroRAF = 0;


heroVideo.addEventListener(
  'loadedmetadata',
  () => {

    videoDuration =
      heroVideo.duration || 0;

    requestHero();

  }
);


heroVideo.addEventListener(
  'timeupdate',
  () => {

    if(!videoDuration){

      videoDuration =
        heroVideo.duration || 0;

    }

  }
);


function updateHero(){

  const maxScroll =
    heroSection.offsetHeight -
    window.innerHeight;


  const rawProgress =
    clamp(
      window.scrollY /
      Math.max(1,maxScroll)
    );


  /*
    First 78% of the scroll:
    control the actual video.
  */

  const videoEnd = .78;


  const videoProgress =
    clamp(
      rawProgress /
      videoEnd
    );


  /*
    Last 22%:
    cinematic transition.
  */

  const transitionProgress =
    smoothstep(
      clamp(
        (rawProgress-videoEnd) /
        (1-videoEnd)
      )
    );


  /*
    VIDEO CURRENT TIME
  */

  if(videoDuration){

    const targetTime =
      videoDuration *
      videoProgress;


    if(
      Math.abs(
        heroVideo.currentTime -
        targetTime
      ) > .015
    ){

      heroVideo.currentTime =
        targetTime;

    }

  }


  /*
    VIDEO PULLS AWAY
  */

  const zoom =
    1 -
    transitionProgress * .56;


  const y =
    transitionProgress * -3;


  heroLayer.style.transform =
    `scale(${zoom}) translate3d(0,${y}%,0)`;


  heroLayer.style.opacity =
    1 -
    transitionProgress * .18;


  heroLayer.style.filter =
    `
      brightness(${1-transitionProgress*.35})
      saturate(${1-transitionProgress*.2})
    `;


  /*
    HERO TEXT DISAPPEARS
  */

  heroContent.style.opacity =
    1 -
    clamp(
      (rawProgress-.45) /
      .25
    );


  heroContent.style.transform =
    `
      translate3d(
        0,
        ${-transitionProgress*20}px,
        0
      )
      scale(
        ${1-transitionProgress*.06}
      )
    `;


  /*
    COVER COMES FROM FAR AWAY
  */

  coverTransition.style.opacity =
    transitionProgress;


  const coverZ =
    -900 +
    900 *
    transitionProgress;


  const coverScale =
    .12 +
    .88 *
    transitionProgress;


  const coverRotation =
    (1-transitionProgress) *
    2;


  coverCard.style.transform =
    `
      translateZ(${coverZ}px)
      scale(${coverScale})
      rotateX(${coverRotation}deg)
    `;


  heroRAF = 0;

}


function requestHero(){

  if(!heroRAF){

    heroRAF =
      requestAnimationFrame(
        updateHero
      );

  }

}


window.addEventListener(
  'scroll',
  requestHero,
  {passive:true}
);


window.addEventListener(
  'resize',
  requestHero
);


requestHero();



