$('#photoInput').onchange = e => {

  const f =
    e.target.files[0];

  if(!f) return;


  if(
    ![
      'image/jpeg',
      'image/png',
      'image/webp'
    ].includes(f.type)
    ||
    f.size > 10 * 1024 * 1024
  ){

    alert(
      'Please select a JPG, PNG or WEBP image up to 10 MB.'
    );

    e.target.value = '';

    return;

  }


  const r =
    new FileReader();


  r.onload = () => {

    photoData =
      r.result;

    $('#photoPreview').src =
      photoData;

    $('#photoPreview')
      .style.display = 'block';

    $('.photo-empty')
      .style.display = 'none';

  };


  r.readAsDataURL(f);

};


