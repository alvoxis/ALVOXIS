let lang =
  localStorage.getItem('alvoxisLang') || 'en';


const $ = selector =>
  document.querySelector(selector);


const $$ = selector =>
  [...document.querySelectorAll(selector)];


const tr = key =>
  (T[lang] && T[lang][key]) ||
  T.en[key] ||
  key;


function clamp(
  value,
  min = 0,
  max = 1
){
  return Math.min(
    max,
    Math.max(min,value)
  );
}


function smoothstep(value){

  value = clamp(value);

  return value * value *
    (3 - 2 * value);

}



