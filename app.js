/* CART */

function saveCart(){

  localStorage.setItem(
    'alvoxisCartV2',
    JSON.stringify(cart)
  );

  renderCart();

}


function renderCart(){

  const box =
    $('#cartItems');


  $('#cartCount').textContent =
    cart.reduce(
      (n,x) => n + x.qty,
      0
    );


  if(!cart.length){

    box.innerHTML =
      '<p class="backend-note">Your cart is empty.</p>';

    $('#cartTotal').textContent =
      '€0.00';

    return;

  }


  box.innerHTML =
    cart.map((x,i) => `

      <div class="cart-item">

        <img
          src="${x.image}"
          alt=""
        >

        <div>

          <b>
            ${x.product}
          </b>

          <small>
            A4 · 120 pieces<br>
            A6 greeting card<br>
            ${x.message ? x.message : 'No message'}
          </small>

        </div>

        <div>

          <b>
            €${x.price.toFixed(2)}
          </b>

          <br>

          <button
            class="remove-item"
            data-i="${i}"
          >
            REMOVE
          </button>

        </div>

      </div>

    `).join('');


  $('#cartTotal').textContent =
    '€' +
    cart
      .reduce(
        (s,x) =>
          s + x.price * x.qty,
        0
      )
      .toFixed(2);


  $$('.remove-item').forEach(b => {

    b.onclick = () => {

      cart.splice(
        +b.dataset.i,
        1
      );

      saveCart();

    };

  });

}


