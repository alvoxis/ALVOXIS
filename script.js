let lang =
  localStorage.getItem("alvoxisLang") || "en";


let selected = null;


let cart =
  JSON.parse(
    localStorage.getItem("alvoxisCart") || "[]"
  );


const $ = selector =>
  document.querySelector(selector);


const $$ = selector =>
  document.querySelectorAll(selector);


function t(key) {

  return (
    translations[lang]?.[key] ||
    translations.en[key] ||
    key
  );

}


function applyLang() {

  document.documentElement.lang = lang;

  $$("#language option").forEach(option => {

    option.selected =
      option.value === lang;

  });


  $$("[data-i18n]").forEach(element => {

    element.textContent =
      t(element.dataset.i18n);

  });

}


function openModal(id) {

  const modal = $("#" + id);

  if (!modal) return;

  modal.classList.add("open");

  modal.setAttribute(
    "aria-hidden",
    "false"
  );

  document.body.style.overflow = "hidden";

}


function closeModal(id) {

  const modal = $("#" + id);

  if (!modal) return;

  modal.classList.remove("open");

  modal.setAttribute(
    "aria-hidden",
    "true"
  );

  document.body.style.overflow = "";

}


/* LANGUAGE */

$("#language").addEventListener(
  "change",
  event => {

    lang = event.target.value;

    localStorage.setItem(
      "alvoxisLang",
      lang
    );

    applyLang();

  }
);


/* CLOSE BUTTONS */

$$("[data-close]").forEach(button => {

  button.addEventListener(
    "click",
    () => {

      closeModal(
        button.dataset.close
      );

    }
  );

});


/* CLOSE MODAL BY BACKGROUND */

$$(".modal").forEach(modal => {

  modal.addEventListener(
    "click",
    event => {

      if (event.target === modal) {

        closeModal(modal.id);

      }

    }
  );

});


/* PRODUCT PERSONALIZATION */

$$(".personalize").forEach(button => {

  button.addEventListener(
    "click",
    () => {

      selected = {

        product:
          button.dataset.product,

        price:
          Number(button.dataset.price)

      };


      $("#modalProductName").textContent =
        selected.product
          .charAt(0)
          .toUpperCase() +
        selected.product.slice(1);


      $("#photoInput").value = "";

      $("#photoPreview").hidden = true;

      $("#photoPreview").removeAttribute(
        "src"
      );

      $("#cardMessage").value = "";

      $("#charCount").textContent = "0";


      openModal(
        "personalizeModal"
      );

    }
  );

});


/* PHOTO UPLOAD */

$("#photoInput").addEventListener(
  "change",
  event => {

    const file =
      event.target.files[0];

    if (!file) return;


    if (
      file.size >
      10 * 1024 * 1024
    ) {

      alert(
        "Please choose an image up to 10 MB."
      );

      event.target.value = "";

      return;

    }


    const reader =
      new FileReader();


    reader.onload =
      result => {

        $("#photoPreview").src =
          result.target.result;

        $("#photoPreview").hidden =
          false;

      };


    reader.readAsDataURL(file);

  }
);


/* CARD MESSAGE */

$("#cardMessage").addEventListener(
  "input",
  event => {

    $("#charCount").textContent =
      event.target.value.length;

  }
);


